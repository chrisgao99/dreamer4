"""Plot logged training and validation losses for completed 70/30 experiments."""
import json
from pathlib import Path
import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'waymo/eval_results/world_model/dynamic7030_loss_curves'
OUT.mkdir(parents=True, exist_ok=True)
runs = {
    'H15': 'waymo_direct_action_flow_v1_h15_b5_generateall_dyn70static30_v05_scratch100k_phys5_yaw075_huber_bounded_tmax090_lr5e5_rerun_cuda3_20260917',
    'H40': 'waymo_direct_action_flow_v1_h40_b5_generateall_dyn70static30_v05_scratch100k_phys5_yaw075_huber_bounded_tmax090_lr5e5',
}
colors = ['#194e91', '#dc651f', '#168274']
fields = ['flow_loss', 'dynamic_flow_loss', 'static_flow_loss']
labels = ['Balanced total (70/30)', 'Dynamic group', 'Static / low-speed group']
plt.rcParams.update({'font.size': 10, 'axes.spines.top': False, 'axes.spines.right': False})
fig, axes = plt.subplots(2, 2, figsize=(12, 7.5), sharex=True, sharey='col')
sources = []
column_max = [0., 0.]
for row, (name, run) in enumerate(runs.items()):
    source = ROOT / 'waymo/checkpoints' / run / 'metrics.jsonl'
    sources.append(str(source))
    records = [json.loads(line) for line in source.read_text().splitlines()]
    for col, split in enumerate(['train', 'val']):
        ax = axes[row, col]
        records_split = [r for r in records if f'{split}_flow_loss' in r]
        x = np.array([r['step'] for r in records_split]) / 1000
        for field, label, color in zip(fields, labels, colors):
            y = np.array([r[f'{split}_{field}'] for r in records_split])
            column_max[col] = max(column_max[col], float(y.max()))
            if split == 'train':
                # Fifty logs, each covering 20 optimizer steps; no zero padding.
                window = 50
                ax.plot(x, y, color=color, alpha=.08, linewidth=.45)
                ax.plot(x[window-1:], np.convolve(y, np.ones(window)/window, mode='valid'),
                        color=color, linewidth=1.8, label=label)
            else:
                ax.plot(x, y, color=color, linewidth=1.3, marker='.', markersize=4, label=label)
        if split == 'val':
            best = min(records_split, key=lambda r: r['val_flow_loss'])
            bx, by = best['step']/1000, best['val_flow_loss']
            ax.scatter([bx], [by], color=colors[0], marker='*', s=130, zorder=5)
            ax.annotate(f'Best: {bx:g}k, {by:.4f}', xy=(bx, by), xytext=(-95, 28),
                        textcoords='offset points', arrowprops={'arrowstyle': '-', 'color': colors[0]},
                        fontsize=9, bbox={'facecolor': 'white', 'alpha': .9, 'edgecolor': 'none'})
        ax.set_title(f'{name} — {"Training" if split == "train" else "Validation"}')
        ax.set_ylabel('Flow-matching loss (Huber)')
        ax.set_xlim(0, 101)
        ax.set_ylim(bottom=0)
        ax.grid(alpha=.2)
        ax.set_xlabel('Optimizer steps (thousands)')
for col in range(2):
    axes[0, col].set_ylim(0, column_max[col] * 1.06)
handles, names = axes[0, 0].get_legend_handles_labels()
fig.legend(handles, names, loc='upper center', bbox_to_anchor=(.5, .94), ncol=3, frameon=False)
fig.suptitle('Dynamic / static loss balancing: 70% / 30%', fontsize=16, y=.99)
fig.text(.5, .02, 'Training: trailing 1,000-step average; faint lines: logged values. Validation: unsmoothed.\n'
         'Group losses are shown before weighting. These losses are not trajectory ADE.',
         ha='center', fontsize=9, color='#444444')
fig.tight_layout(rect=(0, .08, 1, .88))
for extension in ('png', 'pdf'):
    fig.savefig(OUT / f'dynamic7030_loss_curves.{extension}', dpi=180, bbox_inches='tight')
(OUT / 'README.txt').write_text('Generated by waymo/evaluation/plot_dynamic7030_losses.py\nSources:\n' + '\n'.join(sources) + '\n')
print(OUT / 'dynamic7030_loss_curves.png')
